import test from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs/promises";
import path from "node:path";
import os from "node:os";
import { Library } from "../server/library.mjs";
test("组合标签：全部/任意/排除精确匹配、组合筛选及参数校验", async t => {
  const base = await fs.realpath(await fs.mkdtemp(path.join(os.tmpdir(), "sg-tag-rules-")));
  const dir = path.join(base, "音效"); await fs.mkdir(dir);
  const lib = await new Library(path.join(base, "db")).init(); lib.enqueue = () => {};
  t.after(async () => { lib.db.close(); await fs.rm(base, { recursive: true, force: true }); });
  const root = await lib.addRoot(dir, "sfx");
  for (const name of ["一.wav", "二.wav", "三.wav", "四.wav"]) await fs.writeFile(path.join(dir, name), "fixture");
  const job = lib.scan(root.id); while (job.status === "running") await new Promise(r => setTimeout(r, 10));
  const files = lib.list().items;
  const tags = [["悬疑", "紧张", "纯音乐"], ["悬疑", "人声"], ["紧张", "风"], ["大风", "单引号'标签"]];
  files.forEach((a, i) => lib.patch(a.id, { tags: tags[i] }));
  const count = rules => lib.list({ tagRules: JSON.stringify(rules) }).total;
  assert.equal(count({ all: ["悬疑", "紧张"] }), 1);
  assert.equal(count({ any: ["悬疑", "紧张"] }), 3);
  assert.equal(count({ none: ["人声"] }), 3);
  assert.equal(count({ all: ["悬疑"], any: ["紧张", "纯音乐"], none: ["人声"] }), 1);
  assert.equal(count({ all: ["悬疑"], none: ["悬疑"] }), 0);
  assert.equal(count({ all: ["风"] }), 1);
  assert.equal(count({ any: ["单引号'标签", "x') OR 1=1 --"] }), 1);
  assert.equal(count({}), 4);
  assert.equal(lib.list({ kind: "music", tagRules: JSON.stringify({ all: ["悬疑"] }) }).total, 0);
  assert.equal(lib.list({ tagName: "人声", tagRules: JSON.stringify({ all: ["悬疑"] }) }).total, 1);
  for (const invalid of ["bad", "[]", "null", '{"all":"悬疑"}', '{"unknown":[]}', JSON.stringify({ any: Array(21).fill("标签") }), JSON.stringify({ none: [""] })]) assert.throws(() => lib.list({ tagRules: invalid }), /组合|标签/);
});
