import test from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { Library } from "../server/library.mjs";
import { Projects } from "../server/projects.mjs";

async function setup(t) {
  const base = await fs.realpath(await fs.mkdtemp(path.join(os.tmpdir(), "sg-projects-")));
  const source = path.join(base, "素材"); await fs.mkdir(source);
  const lib = await new Library(path.join(base, "db")).init(); lib.enqueue = () => {};
  t.after(async () => { lib.db.close(); await fs.rm(base, { recursive: true, force: true }); });
  for (const name of ["风声 音效.wav", "悬疑音乐.mp3", "摄影.jpg", "视频.mp4"]) await fs.writeFile(path.join(source, name), "project fixture");
  const root = await lib.addRoot(source, "mixed"), scan = lib.scan(root.id);
  while (scan.status === "running") await new Promise(r => setTimeout(r, 10));
  return { lib, projects: new Projects(lib).init(), assets: lib.list().items };
}
test("项目：跨媒体候选、重复加入幂等、批量使用与取消、首次使用时间、备注、重启及原文件不变", async t => {
  const { lib, projects, assets } = await setup(t);
  const before = lib.db.prepare("SELECT * FROM assets ORDER BY id").all();
  const p = projects.save(null, { name: "耳机广告", software: "resolve", note: "第一版" });
  assert.equal(projects.list()[0].total, 0);
  assert.equal(projects.add(p.id, { ids: assets.map(a => a.id) }).added, 4);
  assert.deepEqual(projects.add(p.id, { ids: [assets[0].id, assets[0].id] }), { added: 0, alreadyAdded: 1 });
  assert.equal(projects.list()[0].candidates, 4);
  assert.equal(projects.history(assets[0].id)[0].used_at, null);
  const ids = assets.slice(0, 2).map(a => a.id);
  projects.change(p.id, { ids, status: "used" });
  const usedAt = projects.history(ids[0])[0].used_at;
  assert.ok(usedAt > 0); assert.equal(projects.list()[0].used, 2);
  projects.change(p.id, { ids: [ids[0]], status: "candidate" });
  projects.change(p.id, { ids: [ids[0]], status: "used", note: "第1集 · 开场" });
  assert.equal(projects.history(ids[0])[0].used_at, usedAt);
  assert.equal(projects.history(ids[0])[0].source, "manual");
  assert.equal(projects.items(p.id, { status: "used", q: "开场" }).total, 1);
  const second = projects.save(null, { name: "短剧第一集" });
  projects.add(second.id, { ids: [ids[0]] });
  assert.equal(projects.history(ids[0]).length, 2);
  assert.equal(projects.members(p.id).length, 4);
  projects.save(p.id, { name: "耳机广告终版", software: "jianying", note: "备注" });
  assert.ok(projects.history(ids[0]).some(h => h.project_name === "耳机广告终版"));
  assert.equal(new Projects(lib).init().list().length, 2);
  assert.deepEqual(lib.db.prepare("SELECT * FROM assets ORDER BY id").all(), before);
  for (const a of assets) assert.equal(await fs.readFile(a.path, "utf8"), "project fixture");
});
test("项目：移出与删除仅解除关联，离线/废纸篓/清理索引仍保留快照使用记录", async t => {
  const { lib, projects, assets } = await setup(t), id = assets[0].id;
  const p = projects.save(null, { name: "记录保留" });
  projects.add(p.id, { ids: [id] }); projects.change(p.id, { ids: [id], status: "used" });
  lib.db.prepare("UPDATE assets SET online=0 WHERE id=?").run(id);
  assert.equal(projects.items(p.id).items[0].unavailable, true);
  lib.db.prepare("UPDATE assets SET trashed=1 WHERE id=?").run(id);
  assert.equal(projects.history(id)[0].status, "used");
  lib.db.prepare("DELETE FROM assets WHERE id=?").run(id);
  assert.equal(projects.items(p.id).items[0].asset.name, assets[0].name);
  assert.equal(projects.items(p.id, { q: assets[0].name }).total, 1);
  assert.equal(projects.list()[0].used, 1);
  projects.removeItems(p.id, { ids: [id] }); assert.equal(projects.history(id).length, 0);
  projects.add(p.id, { ids: [assets[1].id] }); projects.remove(p.id);
  assert.equal(projects.list().length, 0); assert.equal(projects.history(assets[1].id).length, 0);
  await fs.access(assets[1].path); assert.ok(lib.asset(assets[1].id));
});
test("项目：输入校验、事务回滚、跨项目成员边界与不允许添加废纸篓素材", async t => {
  const { lib, projects, assets } = await setup(t), p = projects.save(null, { name: "安全项目" });
  assert.throws(() => projects.save(null, { name: "安全项目" }), /已存在/);
  for (const name of ["", " ", "a".repeat(121)]) assert.throws(() => projects.save(null, { name }));
  assert.throws(() => projects.save(null, { name: "有效", software: "invalid" }));
  for (const ids of [[], ["missing"], Array(201).fill(assets[0].id)]) assert.throws(() => projects.add(p.id, { ids }));
  projects.add(p.id, { ids: [assets[0].id] });
  assert.throws(() => projects.change(p.id, { ids: assets.slice(0, 2).map(a => a.id), status: "used" }), /不在此项目/);
  assert.equal(projects.history(assets[0].id)[0].status, "candidate");
  assert.throws(() => projects.change(p.id, { ids: [assets[0].id], status: "invalid" }));
  assert.throws(() => projects.change(p.id, { ids: [assets[0].id], note: "a".repeat(2001) }));
  lib.db.prepare("UPDATE assets SET trashed=1 WHERE id=?").run(assets[1].id);
  assert.throws(() => projects.add(p.id, { ids: [assets[1].id] }), /废纸篓/);
  const other = projects.save(null, { name: "别的项目" });
  assert.throws(() => projects.change(other.id, { ids: [assets[0].id], status: "used" }));
  assert.equal(projects.items(p.id, { q: "' OR 1=1 --" }).total, 0);
});
test("项目类型：音乐/音效/照片/视频按实际类型统计，组合搜索和状态、变更类型及离线快照", async t => {
  const { lib, projects, assets } = await setup(t);
  const p = projects.save(null, { name: "分类项目" });
  const audio = assets.filter(a => ["music", "sfx"].includes(a.kind));
  lib.patch(audio[0].id, { kind: "music" });
  lib.patch(audio[1].id, { kind: "sfx" });
  projects.add(p.id, { ids: assets.map(a => a.id) });
  assert.deepEqual(projects.items(p.id).kinds, { all: 4, music: 1, sfx: 1, photo: 1, video: 1 });
  for (const kind of ["music", "sfx", "photo", "video"]) {
    const result = projects.items(p.id, { kind });
    assert.equal(result.total, 1); assert.equal(result.items[0].asset.kind, kind);
    assert.equal(result.kinds.all, 4, "类型筛选不锁住其他类型的数量");
  }
  const photo = assets.find(a => a.kind === "photo");
  projects.change(p.id, { ids: [photo.id], status: "used", note: "广告开场" });
  assert.deepEqual(projects.items(p.id, { status: "candidate" }).kinds, { all: 3, music: 1, sfx: 1, photo: 0, video: 1 });
  assert.equal(projects.items(p.id, { status: "used", kind: "photo", q: "开场" }).total, 1);
  assert.equal(projects.items(p.id, { status: "used", kind: "sfx", q: "开场" }).total, 0);
  lib.db.prepare("DELETE FROM assets WHERE id=?").run(photo.id);
  assert.equal(projects.items(p.id, { kind: "photo" }).items[0].unavailable, true);
  lib.patch(audio[0].id, { kind: "video" });
  assert.equal(projects.items(p.id).kinds.video, 2);
  assert.equal(projects.items(p.id).kinds.music, 0);
  assert.throws(() => projects.items(p.id, { kind: "bad" }), /素材类型/);
  assert.throws(() => projects.items(p.id, { kind: "' OR 1=1" }), /素材类型/);
});
test("项目类型：统计及过滤覆盖完整项目，不局限于当前60条分页", async t => {
  const { lib, projects, assets } = await setup(t);
  const source = path.dirname(assets[0].path);
  for (let i = 0; i < 65; i++) await fs.writeFile(path.join(source, `分页音效-${i}.wav`), "fixture");
  const scan = lib.scan(lib.roots()[0].id);
  while (scan.status === "running") await new Promise(r => setTimeout(r, 10));
  const p = projects.save(null, { name: "分页分类" });
  const all = lib.db.prepare("SELECT id FROM assets").all();
  projects.add(p.id, { ids: all.map(a => a.id) });
  const photo = assets.find(a => a.kind === "photo");
  lib.db.prepare("UPDATE project_assets SET added_at=1 WHERE project_id=? AND asset_id=?").run(p.id, photo.id);
  const first = projects.items(p.id);
  assert.equal(first.items.length, 60); assert.equal(first.kinds.all, 69);
  assert.equal(first.items.some(i => i.asset.kind === "photo"), false);
  assert.equal(projects.items(p.id, { kind: "photo" }).total, 1);
  assert.equal(projects.items(p.id, { page: 2 }).kinds.photo, 1);
});
