function setup(t) {
  const db=new Database(":memory:");t.after(()=>db.close());
  db.exec(`CREATE TABLE assets (id TEXT PRIMARY KEY,path TEXT,name TEXT,root_id TEXT,kind TEXT,ext TEXT,tags TEXT,trashed INTEGER DEFAULT 0,file_status TEXT DEFAULT 'online',size INTEGER DEFAULT 10,mtime REAL DEFAULT 100,sha256 TEXT,online INTEGER DEFAULT 1)`);
  db.prepare("INSERT INTO assets(id,path,name,root_id,kind,ext,tags) VALUES(?,?,?,?,?,?,?)").run("a1","/managed/风声.wav","风声.wav","active","sfx","wav","[]");
  const lib={db,activeAssetScope:()=>"root_id='active'",nonMissingAssetScope:()=>"file_status<>'missing'",roots:()=>[{id:"active"}],asset(id){const row=db.prepare("SELECT * FROM assets WHERE id=?").get(id);if(!row)throw Error("素材不存在");return {...row,tags:JSON.parse(row.tags)};}};
  const projects=new Projects(lib).init(),project=projects.save(null,{name:"测试项目",software:"resolve"});
  const preview=(value=xml(),timelineId)=>projects.imports.preview(project.id,{xml:value,timelineId},"session");
  const apply=(p,extra={})=>projects.imports.apply(project.id,{token:p.token,selections:p.rows.map(row=>({key:row.key,assetId:row.assetId,used:!!row.assetId&&row.eligible})),confirmUsed:true,...extra},"session");
  return{db,lib,projects,project,preview,apply};
}
test("FCP7 XML: references, reuse, URL decoding, frames, muted tracks and malformed/security bounds",()=>{
  const parsed=parseResolveXml(xml(clip("c1")+clip("c2","f1","<enabled>FALSE</enabled>")));
  assert.equal(parsed.entries.length,1);assert.equal(parsed.entries[0].sourcePath,"/managed/风声.wav");
  assert.equal(parsed.entries[0].occurrences.length,2);assert.equal(parsed.entries[0].occurrences[0].start,1);assert.equal(parsed.entries[0].occurrences[0].sourceOut,2);
  assert.equal(parsed.entries[0].occurrences[1].disabled,true);
  assert.equal(parseResolveXml(xml(clip("c1"),"<enabled>FALSE</enabled>")).entries[0].occurrences[0].disabled,true);
  assert.throws(()=>parseResolveXml('<!DOCTYPE xmeml [<!ENTITY x SYSTEM "file:///etc/passwd">]><xmeml/>'),/实体/);
  assert.throws(()=>parseResolveXml('<!DOCTYPE xmeml SYSTEM "https://invalid"><xmeml/>'),/声明/);
  assert.throws(()=>parseResolveXml("<fcpxml/>"),/仅支持/);
  assert.throws(()=>parseResolveXml("<xmeml><sequence></xmeml>"),/无效/);
  assert.throws(()=>parseResolveXml("x".repeat(4*1024*1024+1)),/4MB/);
});
