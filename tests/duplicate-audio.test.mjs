import test from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs/promises";
import path from "node:path";
import os from "node:os";
import { Library } from "../server/library.mjs";
import { MissingFiles } from "../server/missing-files.mjs";
import { DuplicateAudio } from "../server/duplicate-audio.mjs";
async function setup(t) {
  const base = await fs.realpath(await fs.mkdtemp(path.join(os.tmpdir(), "sg-duplicates-")));
  const source = path.join(base, "音频"); await fs.mkdir(source);
  const lib = await new Library(path.join(base, "db")).init(); lib.enqueue = () => {};
  t.after(async () => { lib.db.close(); await fs.rm(base, { recursive: true, force: true }); });
  const root = await lib.addRoot(source, "sfx");
  for (const [name, contents] of [["原版.wav", "same"], ["改名.mp3", "same"], ["不重复.wav", "diff"], ["独立.wav", "unique length"]]) await fs.writeFile(path.join(source, name), contents);
  const job = lib.scan(root.id); while (job.status === "running") await new Promise(r => setTimeout(r, 10));
  new MissingFiles(lib);
  return { lib, source, detector: new DuplicateAudio(lib) };
}
async function detect(detector, options = {}) {
  detector.start({ scope: "sfx", ...options });
  while (detector.active) await new Promise(r => setTimeout(r, 10));
  assert.equal(detector.lastJob.status, "done", detector.lastJob.error);
  return detector.state(options.scope || "sfx").report;
}
test("重复音频：同大小不同内容不误判、缓存与重启持久化、保留元数据和幂等标记", async t => {
  const { lib, source, detector } = await setup(t);
  const asset = lib.list({ q: "原版.wav" }).items[0]; lib.patch(asset.id, { tags: ["原标签"], note: "保留", confirmed: 1 });
  const report = await detect(detector);
  assert.equal(report.groups.length, 1); assert.equal(report.duplicateFiles, 2); assert.equal(report.extraCopies, 1); assert.equal(report.extraBytes, 4);
  assert.equal(report.groups[0].files.some(f => f.name === "不重复.wav"), false);
  assert.equal(report.hashed, 3);
  const reloaded = new DuplicateAudio(lib);
  assert.equal(reloaded.state("sfx").report.id, report.id);
  assert.equal((await detect(reloaded)).cached, 3);
  const fresh = await detect(reloaded, { force: true }); assert.equal(fresh.cached, 0); assert.equal(fresh.hashed, 3);
  assert.equal((await reloaded.mark({ scope: "sfx", reportId: fresh.id })).marked, 2);
  assert.ok([...lib.jobs.values()].every(job => Array.isArray(job.errors)), "所有任务都必须提供错误列表，防止目录与任务弹窗崩溃");
  assert.deepEqual(lib.asset(asset.id).tags, ["原标签", "重复音频"]);
  assert.equal(lib.asset(asset.id).note, "保留"); assert.equal(lib.asset(asset.id).confirmed, 1);
  assert.equal((await reloaded.mark({ scope: "sfx", reportId: fresh.id })).alreadyMarked, 2);
  assert.equal(await fs.readFile(path.join(source, "原版.wav"), "utf8"), "same");
  await assert.rejects(reloaded.mark({ scope: "sfx", reportId: "old" }), /结果已变化/);
});
test("重复音频：变化/离线保护、跨音效音乐范围、取消与忙碌保护", async t => {
  const { lib, source, detector } = await setup(t);
  const renamed = lib.list({ q: "改名.mp3" }).items[0];
  const report = await detect(detector);
  await fs.writeFile(renamed.path, "changed");
  const skipped = await detector.mark({ scope: "sfx", reportId: report.id });
  assert.equal(skipped.marked, 0); assert.equal(skipped.skipped.length, 1);
  assert.equal(lib.asset(renamed.id).tags.includes("重复音频"), false);
  await fs.writeFile(renamed.path, "same"); lib.patch(renamed.id, { kind: "music" });
  assert.equal((await detect(detector)).groups.length, 0);
  assert.equal((await detect(detector, { scope: "all" })).groups.length, 1);
  detector.start({ scope: "all" }); detector.cancel();
  while (detector.active) await new Promise(r => setTimeout(r, 10));
  assert.equal(detector.lastJob.status, "cancelled"); assert.ok(detector.state("all").report);
  assert.throws(() => new DuplicateAudio(lib, () => true).start(), /任务/);
  assert.throws(() => detector.start({ scope: "video" }), /请选择/);
  await fs.rename(source, source + "-offline");
  const offline = await detect(detector, { scope: "all" }); assert.equal(offline.skipped.length, 4); assert.equal(offline.groups.length, 0);
});
test("重复音频：标签上限整组跳过；备份失败不写标签；越界链接不读取", async t => {
  const { lib, source, detector } = await setup(t);
  const original = lib.list({ q: "原版.wav" }).items[0], copy = lib.list({ q: "改名.mp3" }).items[0];
  lib.patch(original.id, { tags: Array.from({ length: 40 }, (_, i) => "标签" + i) });
  const report = await detect(detector);
  const marked = await detector.mark({ scope: "sfx", reportId: report.id });
  assert.equal(marked.marked, 0); assert.equal(marked.skipped.length, 1);
  assert.equal(lib.asset(copy.id).tags.length, 0);
  lib.patch(original.id, { tags: [] });
  const backupDir = path.join(lib.dataDir, "backups");
  await fs.rm(backupDir, { recursive: true }); await fs.writeFile(backupDir, "阻止备份");
  await assert.rejects(detector.mark({ scope: "sfx", reportId: report.id }));
  assert.equal(lib.asset(original.id).tags.length, 0); assert.equal(lib.asset(copy.id).tags.length, 0);
  const outside = path.join(source, "..", "越界.wav"); await fs.writeFile(outside, "same");
  await fs.unlink(copy.path); await fs.symlink(outside, copy.path);
  const blocked = await detect(detector, { force: true }); assert.equal(blocked.groups.length, 0);
  assert.equal(blocked.skipped.some(f => f.id === copy.id), true);
});
test("重复报告排除已删除记录、同步统计与元数据；恢复后重新显示", async t => {
  const { lib, detector } = await setup(t);
  const original = lib.list({ q: "原版.wav" }).items[0], copy = lib.list({ q: "改名.mp3" }).items[0];
  const report = await detect(detector);
  lib.patch(original.id, { tags: ["新标签"], note: "不删除" });
  assert.deepEqual(detector.state("sfx").report.groups[0].files.find(f => f.id === original.id).tags, ["新标签"]);
  lib.db.prepare("UPDATE assets SET trashed=1,online=0 WHERE id=?").run(copy.id);
  const view = detector.state("sfx").report;
  assert.equal(view.groups.length, 0); assert.equal(view.duplicateFiles, 0); assert.equal(view.extraBytes, 0);
  assert.equal((await detector.mark({ scope: "sfx", reportId: report.id })).marked, 0);
  assert.deepEqual(lib.asset(original.id).tags, ["新标签"]);
  lib.db.prepare("UPDATE assets SET trashed=0,online=1 WHERE id=?").run(copy.id);
  assert.equal(detector.state("sfx").report.groups.length, 1);
  assert.equal((await detector.mark({ scope: "sfx", reportId: report.id })).marked, 2);
  assert.equal(detector.state().report.duplicateFiles, 2);
});
test("删除重复音频：三份剩两份保留标签，剩一份只移除重复标签，备份且幂等", async t => {
  const { lib, source, detector } = await setup(t);
  await fs.writeFile(path.join(source, "第三份.wav"), "same");
  const scan = lib.scan(lib.roots()[0].id);
  while (scan.status === "running") await new Promise(r => setTimeout(r, 10));
  const report = await detect(detector);
  const [a, b, c] = report.groups[0].files;
  lib.patch(a.id, { tags: ["原标签"], note: "保留备注", favorite: 1, confirmed: 1 });
  await detector.mark({ scope: "sfx", reportId: report.id });
  lib.db.prepare("UPDATE assets SET trashed=1,online=0 WHERE id=?").run(c.id);
  assert.equal((await detector.reconcileTrash([c.id])).removed, 0);
  assert.ok(lib.asset(a.id).tags.includes("重复音频"));
  assert.ok(lib.asset(b.id).tags.includes("重复音频"));
  lib.db.prepare("UPDATE assets SET trashed=1,online=0 WHERE id=?").run(b.id);
  assert.equal((await detector.reconcileTrash([b.id])).removed, 1);
  assert.deepEqual(lib.asset(a.id).tags, ["原标签"]);
  assert.equal(lib.asset(a.id).note, "保留备注");
  assert.equal(lib.asset(a.id).favorite, 1);
  assert.equal(lib.asset(a.id).confirmed, 1);
  assert.ok(lib.asset(b.id).tags.includes("重复音频"));
  assert.equal((await detector.reconcileTrash([b.id])).removed, 0);
  const files = (await fs.readdir(path.join(lib.dataDir, "backups"))).filter(n => n.startsWith("duplicate-audio-tag-cleanup-"));
  assert.equal(files.length, 1);
  const backupPath = path.join(lib.dataDir, "backups", files[0]);
  const backup = JSON.parse(await fs.readFile(backupPath, "utf8"));
  assert.deepEqual(backup.assets[0].tags, ["原标签", "重复音频"]);
  assert.equal((await fs.stat(backupPath)).mode & 0o777, 0o600);
  assert.equal(await fs.readFile(a.path, "utf8"), "same");
});
test("删除重复音频：合并所有范围，离线、改名和改类型不误清；备份失败不改标签", async t => {
  const { lib, source, detector } = await setup(t);
  const report = await detect(detector);
  const [a, b] = report.groups[0].files;
  await detector.mark({ scope: "sfx", reportId: report.id });
  lib.db.prepare("UPDATE assets SET online=0 WHERE id=?").run(b.id);
  lib.patch(b.id, { kind: "music" });
  assert.equal(detector.state("sfx").report.groups.length, 0);
  assert.equal((await detector.reconcileTrash([b.id])).removed, 0);
  assert.ok(lib.asset(a.id).tags.includes("重复音频"));
  const all = await detect(detector, { scope: "all" });
  assert.equal(all.groups.length, 1);
  await fs.writeFile(path.join(source, "跨范围第三份.wav"), "same");
  const scan = lib.scan(lib.roots()[0].id);
  while (scan.status === "running") await new Promise(r => setTimeout(r, 10));
  await detect(detector, { scope: "all" });
  lib.db.prepare("UPDATE assets SET trashed=1 WHERE id=?").run(b.id);
  assert.equal((await detector.reconcileTrash([b.id])).removed, 0, "其他范围还有未删除副本");
  const third = lib.list({ q: "跨范围第三份" }).items[0];
  lib.db.prepare("UPDATE assets SET trashed=1 WHERE id=?").run(third.id);
  const directory = path.join(lib.dataDir, "backups");
  await fs.rm(directory, { recursive: true }); await fs.writeFile(directory, "阻止备份");
  await assert.rejects(detector.reconcileTrash([b.id]));
  assert.ok(lib.asset(a.id).tags.includes("重复音频"));
});
